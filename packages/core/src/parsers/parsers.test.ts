import { describe, it, expect } from 'vitest';
import {
  OrcaSlicerParser,
  CuraParser,
  PrusaParser,
  CrealityParser,
  parseSlicerFile,
  parseTimeString,
} from './index.js';

describe('Parsers de Slicers', () => {
  describe('parseTimeString', () => {
    it('debe parsear horas, minutos y segundos correctamente', () => {
      expect(parseTimeString('2h 30m')).toBe(2.5);
      expect(parseTimeString('1h 15m 30s')).toBeCloseTo(1.2583, 3);
      expect(parseTimeString('1d 2h')).toBe(26);
      expect(parseTimeString('45m')).toBe(0.75);
    });
  });

  describe('OrcaSlicerParser', () => {
    const parser = new OrcaSlicerParser();
    const orcaSample = `
; generated by OrcaSlicer 2.1.1 on 2026-10-28
; estimated printing time (normal mode) = 3h 45m 10s
; total filament used [g] = 85.5
; total filament used [mm] = 28420.1
M73 P0 R225
G21
G90
`;

    it('debe reconocer archivo de OrcaSlicer', () => {
      expect(parser.canParse(orcaSample)).toBe(true);
    });

    it('debe extraer tiempo y filamento de OrcaSlicer', () => {
      const res = parser.parse(orcaSample, 'pieza_test.gcode');
      expect(res).not.toBeNull();
      expect(res?.slicerName).toBe('OrcaSlicer');
      expect(res?.printTimeHours).toBeCloseTo(3.75, 1);
      expect(res?.filamentGrams).toBe(85.5);
      expect(res?.sourceFile).toBe('pieza_test.gcode');
    });

    it('debe reconocer Bambu Studio si está en el encabezado', () => {
      const bambuSample = `
; generated by BambuStudio 01.09.03.50
; estimated printing time (normal mode) = 1h 30m
; filament used [g] = 42.0
`;
      const res = parser.parse(bambuSample);
      expect(res?.slicerName).toBe('Bambu Studio');
      expect(res?.printTimeHours).toBe(1.5);
      expect(res?.filamentGrams).toBe(42.0);
    });
  });

  describe('CuraParser', () => {
    const parser = new CuraParser();
    const curaSample = `
;FLAVOR:Marlin
;TIME:7200
;Filament used: 15.5m
;Generated with Cura_SteamEngine 5.6.0
M140 S60
M105
`;

    it('debe reconocer archivo de Cura', () => {
      expect(parser.canParse(curaSample)).toBe(true);
    });

    it('debe convertir segundos a horas y metros a gramos', () => {
      const res = parser.parse(curaSample);
      expect(res).not.toBeNull();
      expect(res?.slicerName).toBe('UltiMaker Cura');
      expect(res?.printTimeHours).toBe(2.0); // 7200s / 3600
      expect(res?.filamentGrams).toBeGreaterThan(40);
    });
  });

  describe('PrusaParser', () => {
    const parser = new PrusaParser();
    const prusaSample = `
; generated by PrusaSlicer 2.8.0 on 2026-10-28
; estimated printing time (normal mode) = 2h 15m
; filament used [g] = 55.4
; filament used [cm3] = 44.6
`;

    it('debe reconocer archivo de PrusaSlicer', () => {
      expect(parser.canParse(prusaSample)).toBe(true);
    });

    it('debe extraer tiempo y gramos correctamente', () => {
      const res = parser.parse(prusaSample);
      expect(res?.slicerName).toBe('PrusaSlicer');
      expect(res?.printTimeHours).toBe(2.25);
      expect(res?.filamentGrams).toBe(55.4);
    });
  });

  describe('CrealityParser', () => {
    const parser = new CrealityParser();
    const crealitySample = `
; generated by Creality Print v5.0
; estimated printing time = 1h 20m
; filament used [g] = 30.5
`;

    it('debe reconocer archivo de Creality Print', () => {
      expect(parser.canParse(crealitySample)).toBe(true);
    });

    it('debe extraer tiempo y gramos', () => {
      const res = parser.parse(crealitySample);
      expect(res?.slicerName).toBe('Creality Print');
      expect(res?.printTimeHours).toBeCloseTo(1.33, 1);
      expect(res?.filamentGrams).toBe(30.5);
    });
  });

  describe('Universal parseSlicerFile', () => {
    it('debe detectar automáticamente el slicer correspondiente', () => {
      const gcode = `; generated by OrcaSlicer\n; estimated printing time = 4h 0m\n; filament used [g] = 120.0`;
      const res = parseSlicerFile(gcode, 'robot.gcode');
      expect(res?.slicerName).toBe('OrcaSlicer');
      expect(res?.printTimeHours).toBe(4);
      expect(res?.filamentGrams).toBe(120);
    });

    it('debe manejar G-Code genérico con etiquetas de tiempo y peso', () => {
      const generic = `
;TIME:3600
;filament used [g] = 25.0
G1 X10 Y10
`;
      const res = parseSlicerFile(generic);
      expect(res?.printTimeHours).toBe(1.0);
      expect(res?.filamentGrams).toBe(25.0);
    });

    it('debe parsear metadatos directos generados por plugins/scripts Slice2Price', () => {
      const pluginOutput = `;Slice2Price_JSON: {"slicerName":"OrcaSlicer Script","pieceName":"Engranaje","printTimeHours":2.5,"filamentGrams":45.2}`;
      const res = parseSlicerFile(pluginOutput);
      expect(res?.slicerName).toBe('OrcaSlicer Script');
      expect(res?.sourceFile).toBe('Engranaje');
      expect(res?.printTimeHours).toBe(2.5);
      expect(res?.filamentGrams).toBe(45.2);
    });

    it('debe retornar null para contenido sin información relevante', () => {
      const empty = `G28\nG1 Z10\nM104 S0\nM140 S0`;
      expect(parseSlicerFile(empty)).toBeNull();
    });

    it('debe manejar PrusaSlicer con estadísticas al pie en archivos grandes', () => {
      const gcodeLargePrusa = `; generated by PrusaSlicer 2.7.1
G21
G90
; ... [SLICE2PRICE_OMITTED_MIDDLE] ...
; estimated printing time (normal mode) = 3h 15m 20s
; filament used [g] = 52.4
; total filament used [g] = 52.4
`;
      const res = parseSlicerFile(gcodeLargePrusa, 'grande_prusa.gcode');
      expect(res).not.toBeNull();
      expect(res?.slicerName).toBe('PrusaSlicer');
      expect(res?.printTimeHours).toBeCloseTo(3.25, 1);
      expect(res?.filamentGrams).toBe(52.4);
    });

    it('debe manejar Cura con filamento en gramos directamente', () => {
      const curaGrams = `;Generated with Cura_SteamEngine 5.6.0
;TIME:7200
;Filament used: 34.8g
M104 S200
`;
      const res = parseSlicerFile(curaGrams, 'cura_pieza.gcode');
      expect(res).not.toBeNull();
      expect(res?.slicerName).toBe('UltiMaker Cura');
      expect(res?.printTimeHours).toBe(2.0);
      expect(res?.filamentGrams).toBe(34.8);
    });

    it('debe manejar de forma segura archivos .3mf sin laminar retornando null sin lanzar excepción', () => {
      const unSliced3mf = 'PK\x03\x04...[Metadatos 3D sin laminar]...';
      const res = parseSlicerFile(unSliced3mf, 'modelo_cad.3mf');
      expect(res).toBeNull();
    });

    it('debe leer Bambu Studio con separador dos puntos y etiquetas de peso (Falla E2)', () => {
      const bambuGCode = `; HEADER_BLOCK_START
; generated by BambuStudio 01.09.01.40
; total filament weight [g] : 18.45
; total estimated time: 1h 12m 30s
; HEADER_BLOCK_END
G90
G21
M104 S220
`;
      const res = parseSlicerFile(bambuGCode, 'pieza_bambu.gcode');
      expect(res).not.toBeNull();
      expect(res?.slicerName).toBe('Bambu Studio');
      expect(res?.filamentGrams).toBe(18.5); // Redondeado a 1 decimal
      expect(res?.printTimeHours).toBeCloseTo(1.21, 2);
    });

    it('debe rechazar Slice2Price_JSON con ceros y no devolver detección falsa (Falla E2b)', () => {
      const invalidJson = `;Slice2Price_JSON: {"slicerName":"Bambu Studio","pieceName":"Test","printTimeHours":0,"filamentGrams":0}`;
      const res = parseSlicerFile(invalidJson);
      expect(res).toBeNull();
    });

    it('debe interpretar correctamente unidades mm en lugar de tratarlas como metros (Falla E5)', () => {
      const curaMm = `;Generated with Cura_SteamEngine 5.6.0
;TIME:3600
;Filament used: 3200mm
`;
      const res = parseSlicerFile(curaMm, 'test_mm.gcode');
      expect(res).not.toBeNull();
      // 3200 mm de filamento 1.75mm de densidad 1.24 = ~9.5g (NO 9.544g / 9.5kg de haber sido 3200m)
      expect(res?.filamentGrams).toBeCloseTo(9.5, 0);
      expect(res?.filamentGrams).toBeLessThan(50);
    });

    it('debe respetar la densidad del material activo al convertir metros o mm a gramos (Falla E5b)', () => {
      const curaGcode = `;Generated with Cura_SteamEngine 5.6.0
;TIME:3600
;Filament used: 10.0m
`;
      // Densidad PLA 1.24 g/cm3 vs ABS 1.04 g/cm3 (10m = 10000mm)
      // Volumen = PI * (0.175/2)^2 * 1000 = ~24.05 cm3
      // PLA (1.24): ~29.8g | ABS (1.04): ~25.0g
      const resPla = parseSlicerFile(curaGcode, 'test.gcode', { density: 1.24 });
      const resAbs = parseSlicerFile(curaGcode, 'test.gcode', { density: 1.04 });

      expect(resPla?.filamentGrams).toBeCloseTo(29.8, 0);
      expect(resAbs?.filamentGrams).toBeCloseTo(25.0, 0);
      expect(resAbs?.filamentGrams).toBeLessThan(resPla?.filamentGrams ?? 0);
    });

    it('no debe clasificar erróneamente OrcaSlicer como PrusaSlicer aunque contenga comentarios heredados', () => {
      const orcaWithInheritedComments = `; generated by OrcaSlicer 1.9.0
; estimated printing time (normal mode) = 2h 00m 00s
; filament used [g] = 30.0
; ... [SLICE2PRICE_OMITTED_MIDDLE] ...
; prusaslicer_compatible_settings = 1
; slic3r_version = 2.7.0
`;
      const res = parseSlicerFile(orcaWithInheritedComments, 'orca_export.gcode');
      expect(res?.slicerName).toBe('OrcaSlicer');
    });

    it('debe leer metadatos de archivos .3mf laminados reales con formato XML y bytes puros (Fallas E3 / E3b)', async () => {
      const { zipSync, strToU8 } = await import('fflate');
      const xmlBambuConfig = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header>
    <header_item key="prediction" value="8100"/>
    <header_item key="weight" value="42.6"/>
  </header>
  <plate>
    <metadata key="prediction" value="8100"/>
    <metadata key="weight" value="42.6"/>
  </plate>
</config>`;

      const zipBytes = zipSync({
        'Metadata/slice_info.config': strToU8(xmlBambuConfig),
      });

      // Pasar como Uint8Array binario directo (sin pasar por toString utf-8 corruptor)
      const res = parseSlicerFile(zipBytes, 'modelo_bambu_real.3mf');
      expect(res).not.toBeNull();
      expect(res?.slicerName).toContain('3MF');
      expect(res?.printTimeHours).toBe(2.25);
      expect(res?.filamentGrams).toBe(42.6);
    });

    it('debe sumar el tiempo y peso de todas las placas en archivos .3mf multi-placa (Hallazgo S1) y omitir modelos 3D pesados (Hallazgo S3)', async () => {
      const { zipSync, strToU8 } = await import('fflate');
      const xmlMultiPlateConfig = `<?xml version="1.0" encoding="UTF-8"?>
<config>
  <header>
    <header_item key="X-BBL-Client-Type" value="slicer"/>
  </header>
  <plate>
    <metadata key="index" value="1"/>
    <metadata key="prediction" value="3600"/>
    <metadata key="weight" value="10.0"/>
  </plate>
  <plate>
    <metadata key="index" value="2"/>
    <metadata key="prediction" value="7200"/>
    <metadata key="weight" value="20.0"/>
  </plate>
</config>`;

      // Simulamos paquete 3MF que contiene geometría 3D pesada y metadatos de slice
      const zipBytes = zipSync({
        'Metadata/slice_info.config': strToU8(xmlMultiPlateConfig),
        '3D/3dmodel.model': strToU8('<model><vertices>...</vertices></model>'),
      });

      const res = parseSlicerFile(zipBytes, 'proyecto_multiplaca.3mf');
      expect(res).not.toBeNull();
      // Tiempo total: 3600s + 7200s = 10800s (3 horas)
      expect(res?.printTimeHours).toBe(3.0);
      // Peso total: 10.0g + 20.0g = 30.0g
      expect(res?.filamentGrams).toBe(30.0);
      // Detecta que tiene 2 placas
      expect(res?.slicerName).toContain('2 placas');
    });
  });
});
