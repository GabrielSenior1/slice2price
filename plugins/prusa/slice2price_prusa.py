#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Slice2Price — Script de Post-Procesamiento para PrusaSlicer
Transmite automáticamente el tiempo de impresión y peso de material calculados
por PrusaSlicer hacia Slice2Price.

Uso en PrusaSlicer:
Configuración de impresión -> Opciones de salida -> Scripts de post-procesamiento:
"python C:\\ruta\\a\\Slice2Price\\plugins\\prusa\\slice2price_prusa.py;"
"""

import sys
import os
import re
import json
import time

def parse_time_str(time_str):
    total_hours = 0.0
    d = re.search(r'(\d+)\s*d', time_str)
    h = re.search(r'(\d+)\s*h', time_str)
    m = re.search(r'(\d+)\s*m', time_str)
    s = re.search(r'(\d+)\s*s', time_str)
    if d: total_hours += float(d.group(1)) * 24.0
    if h: total_hours += float(h.group(1))
    if m: total_hours += float(m.group(1)) / 60.0
    if s: total_hours += float(s.group(1)) / 3600.0
    return round(total_hours, 2)

def main():
    if len(sys.argv) < 2:
        return

    gcode_path = sys.argv[1]
    if not os.path.exists(gcode_path):
        return

    model_name = os.path.splitext(os.path.basename(gcode_path))[0]

    print_time_hours = 0.0
    filament_grams = 0.0

    try:
        # Leer cabecera y pie del G-Code para obtener métricas
        with open(gcode_path, 'r', encoding='utf-8', errors='ignore') as f:
            lines = f.readlines()

        # Buscar de abajo hacia arriba (donde PrusaSlicer escribe el resumen)
        for line in reversed(lines[-250:]):
            if '; estimated printing time' in line:
                match = re.search(r'estimated printing time[^\r\n=]*=\s*([^\r\n;]+)', line)
                if match:
                    print_time_hours = parse_time_str(match.group(1))
            elif 'filament used [g]' in line:
                match = re.search(r'filament used \[g\]\s*=\s*([0-9.]+)', line)
                if match:
                    filament_grams = round(float(match.group(1)), 2)

        if print_time_hours == 0.0 and filament_grams == 0.0:
            # Buscar en las primeras 250 líneas
            for line in lines[:250]:
                if '; estimated printing time' in line:
                    match = re.search(r'estimated printing time[^\r\n=]*=\s*([^\r\n;]+)', line)
                    if match:
                        print_time_hours = parse_time_str(match.group(1))
                elif 'filament used [g]' in line:
                    match = re.search(r'filament used \[g\]\s*=\s*([0-9.]+)', line)
                    if match:
                        filament_grams = round(float(match.group(1)), 2)

        payload = {
            "slicerName": "PrusaSlicer",
            "pieceName": model_name,
            "printTimeHours": print_time_hours,
            "filamentGrams": filament_grams,
            "timestamp": int(time.time()),
        }

        # Escribir en la carpeta puente de Slice2Price
        temp_dir = os.environ.get("TEMP") or os.environ.get("TMP") or "/tmp"
        bridge_dir = os.path.join(temp_dir, "Slice2Price")
        os.makedirs(bridge_dir, exist_ok=True)

        bridge_file = os.path.join(bridge_dir, f"{model_name}.gcode.txt")
        with open(bridge_file, "w", encoding="utf-8") as bf:
            bf.write(f"; generated by PrusaSlicer\n")
            bf.write(f"; estimated printing time = {print_time_hours}h\n")
            bf.write(f"; filament used [g] = {filament_grams}\n")
            bf.write(f";Slice2Price_JSON: {json.dumps(payload)}\n")

    except Exception as e:
        # Los scripts de post-procesamiento no deben interrumpir a PrusaSlicer
        pass

if __name__ == '__main__':
    main()

